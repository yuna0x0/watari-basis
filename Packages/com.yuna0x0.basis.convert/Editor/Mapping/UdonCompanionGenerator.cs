using System.Collections.Generic;
using System.Text;
using yuna0x0.Basis.Convert.Model;

namespace yuna0x0.Basis.Convert.Mapping
{
    /// <summary>
    /// Writes the partial class that joins a converted UdonSharp script and gives the runtime
    /// package what Cilbox cannot work out by reflection: calls by name, variable access by name,
    /// the synced-field serializer, and the capability flags the runtime's driver reads.
    /// <para>
    /// The members it overrides are the runtime package's contract with generated code
    /// (<see cref="ContractVersion"/>). Neither package references the other; this text is the only
    /// link.
    /// </para>
    /// </summary>
    public static class UdonCompanionGenerator
    {
        public const int ContractVersion = 3;

        // Udon exports built-in events as "_" plus lower camel case, and SendCustomEvent reaches them
        // by that name.
        static readonly string[] AliasedEvents =
        {
            "Interact", "OnPickup", "OnDrop", "OnPickupUseDown", "OnPickupUseUp", "OnDeserialization",
            "OnPreSerialization", "PostLateUpdate",
        };

        static readonly string[] AliasedHooks =
        {
            "Start", "Update", "LateUpdate", "FixedUpdate", "OnEnable", "OnDisable", "OnDestroy",
        };

        public static string Generate(UdonScriptData script, string generatorVersion, List<ConversionDiagnostic> diagnostics)
        {
            StringBuilder b = new StringBuilder();
            b.AppendLine("// <auto-generated>");
            b.AppendLine($"// Companion for {script.Name}, written by Watari {generatorVersion}, contract {ContractVersion}.");
            b.AppendLine("// Regenerated on every conversion; edits here are lost.");
            b.AppendLine("// </auto-generated>");
            b.AppendLine("using System.IO;");
            b.AppendLine();

            string indent = "";
            if (!string.IsNullOrEmpty(script.Namespace))
            {
                b.AppendLine("namespace " + script.Namespace);
                b.AppendLine("{");
                indent = "    ";
            }

            string modifiers = script.IsStatic ? "static partial class" : script.IsAbstract ? "abstract partial class" : "partial class";
            b.AppendLine(indent + "[Cilboxable]");
            // No accessibility modifier: the source's declaration sets it, and a differing one on
            // this part would not compile.
            b.AppendLine(indent + modifiers + " " + script.Name);
            b.AppendLine(indent + "{");

            if (script.IsBehaviour)
            {
                string i2 = indent + "    ";
                if (script.UserBaseName == null)
                {
                    // The runtime's base class holds no fields (Cilbox could mis-index them across
                    // assemblies), so the first converted class in a hierarchy stores its state.
                    b.AppendLine(i2 + "private object __udonState;");
                    b.AppendLine(i2 + "public override object __GetState() { return __udonState; }");
                    b.AppendLine(i2 + "public override void __SetState(object state) { __udonState = state; }");
                    b.AppendLine();
                }

                WriteTypeId(b, i2, script);
                WriteLookups(b, i2, script);
                WriteDispatch(b, i2, script);
                WriteCallables(b, i2, script);
                WriteSetVar(b, i2, script);
                WriteGetVar(b, i2, script);
                if (script.HasSyncedFields)
                {
                    WriteSerialize(b, i2, script, diagnostics);
                }

                WriteFlags(b, i2, script, diagnostics);
                WriteHooks(b, i2, script, diagnostics);
            }

            b.AppendLine(indent + "}");
            if (indent.Length > 0)
            {
                b.AppendLine("}");
            }

            return b.ToString();
        }

        static void WriteDispatch(StringBuilder b, string i, UdonScriptData s)
        {
            b.AppendLine(i + "public override bool __Dispatch(string eventName)");
            b.AppendLine(i + "{");
            b.AppendLine(i + "    switch (eventName)");
            b.AppendLine(i + "    {");
            HashSet<string> written = new HashSet<string>();
            foreach (string method in s.EventMethods)
            {
                if (written.Add(method))
                {
                    b.AppendLine($"{i}        case \"{method}\": {method}(); return true;");
                }

                string alias = AliasOf(method, AliasedEvents);
                if (alias != null && written.Add(alias))
                {
                    b.AppendLine($"{i}        case \"{alias}\": {method}(); return true;");
                }
            }

            foreach (string hook in s.DeclaredHooks)
            {
                string alias = AliasOf(hook, AliasedHooks);
                if (alias != null && written.Add(alias))
                {
                    b.AppendLine($"{i}        case \"{alias}\": {hook}(); return true;");
                }
            }

            b.AppendLine(i + "    }");
            b.AppendLine(i + (s.UserBaseName != null ? "    return base.__Dispatch(eventName);" : "    return false;"));
            b.AppendLine(i + "}");
            b.AppendLine();
        }

        static void WriteSetVar(StringBuilder b, string i, UdonScriptData s)
        {
            b.AppendLine(i + "public override bool __SetVar(string symbolName, object value)");
            b.AppendLine(i + "{");
            b.AppendLine(i + "    switch (symbolName)");
            b.AppendLine(i + "    {");
            // UdonSharp runs a FieldChangeCallback setter only when the value changes.
            foreach (UdonFieldData f in s.Fields)
            {
                if (f.CallbackProperty != null)
                {
                    b.AppendLine($"{i}        case \"{f.Name}\": if (!object.Equals({f.Name}, value)) {f.CallbackProperty} = ({f.TypeName})value; return true;");
                }
                else
                {
                    b.AppendLine($"{i}        case \"{f.Name}\": {f.Name} = ({f.TypeName})value; return true;");
                }
            }

            b.AppendLine(i + "    }");
            b.AppendLine(i + (s.UserBaseName != null ? "    return base.__SetVar(symbolName, value);" : "    return false;"));
            b.AppendLine(i + "}");
            b.AppendLine();
        }

        static void WriteGetVar(StringBuilder b, string i, UdonScriptData s)
        {
            b.AppendLine(i + "public override object __GetVar(string symbolName)");
            b.AppendLine(i + "{");
            b.AppendLine(i + "    switch (symbolName)");
            b.AppendLine(i + "    {");
            foreach (UdonFieldData f in s.Fields)
            {
                b.AppendLine($"{i}        case \"{f.Name}\": return {f.Name};");
            }

            b.AppendLine(i + "    }");
            b.AppendLine(i + (s.UserBaseName != null ? "    return base.__GetVar(symbolName);" : "    return null;"));
            b.AppendLine(i + "}");
            b.AppendLine();
        }

        static void WriteSerialize(StringBuilder b, string i, UdonScriptData s, List<ConversionDiagnostic> diagnostics)
        {
            b.AppendLine(i + "public override void __Serialize(BinaryWriter writer)");
            b.AppendLine(i + "{");
            if (s.UserBaseName != null)
            {
                b.AppendLine(i + "    base.__Serialize(writer);");
            }

            foreach (UdonFieldData f in s.Fields)
            {
                if (!f.Synced || f.Wire == UdonWireKind.Unsupported)
                {
                    continue;
                }

                if (f.IsArray)
                {
                    b.AppendLine($"{i}    if ({f.Name} == null) writer.Write(-1);");
                    b.AppendLine($"{i}    else");
                    b.AppendLine($"{i}    {{");
                    b.AppendLine($"{i}        writer.Write({f.Name}.Length);");
                    b.AppendLine($"{i}        for (int i = 0; i < {f.Name}.Length; i++) {Write(f, f.Name + "[i]")}");
                    b.AppendLine($"{i}    }}");
                }
                else
                {
                    b.AppendLine(i + "    " + Write(f, f.Name));
                }
            }

            b.AppendLine(i + "}");
            b.AppendLine();

            b.AppendLine(i + "public override void __Deserialize(BinaryReader reader)");
            b.AppendLine(i + "{");
            if (s.UserBaseName != null)
            {
                b.AppendLine(i + "    base.__Deserialize(reader);");
            }

            int temp = 0;
            foreach (UdonFieldData f in s.Fields)
            {
                if (!f.Synced)
                {
                    continue;
                }

                if (f.Wire == UdonWireKind.Unsupported)
                {
                    diagnostics.Add(DiagnosticSeverity.Dropped, "script.sync.typeDropped",
                        $"{s.Name}.{f.Name} is synced as {f.TypeName}, which the converter cannot serialize; it stays local.");
                    continue;
                }

                string target = f.CallbackProperty ?? f.Name;
                if (f.IsArray)
                {
                    string n = "n" + temp;
                    string a = "a" + temp;
                    temp++;
                    string element = f.TypeName.Substring(0, f.TypeName.Length - 2);
                    b.AppendLine($"{i}    int {n} = reader.ReadInt32();");
                    b.AppendLine($"{i}    {f.TypeName} {a} = {n} < 0 ? null : new {element}[{n}];");
                    b.AppendLine($"{i}    for (int i = 0; i < {n}; i++) {a}[i] = {Read(f)};");
                    b.AppendLine($"{i}    {target} = {a};");
                }
                else if (f.CallbackProperty != null)
                {
                    string v = "v" + temp;
                    temp++;
                    b.AppendLine($"{i}    {f.TypeName} {v} = {Read(f)};");
                    b.AppendLine($"{i}    if (!object.Equals({f.Name}, {v})) {target} = {v};");
                }
                else
                {
                    b.AppendLine($"{i}    {target} = {Read(f)};");
                }
            }

            b.AppendLine(i + "}");
            b.AppendLine();
        }

        static void WriteFlags(StringBuilder b, string i, UdonScriptData s, List<ConversionDiagnostic> diagnostics)
        {
            int mode;
            switch (s.SyncMode)
            {
                case "None": mode = 0; break;
                case "NoVariableSync": mode = 1; break;
                case "Continuous": mode = 2; break;
                case "Manual": mode = 3; break;
                default:
                    // "Any" leaves the choice to the inspector, which the source scene records on the
                    // backing UdonBehaviour. Until that is read: Manual with synced fields, network
                    // events only without.
                    mode = s.HasSyncedFields ? 3 : 1;
                    if (s.HasSyncedFields)
                    {
                        diagnostics.Add(DiagnosticSeverity.Approximated, "script.sync.anyAsManual",
                            $"{s.Name} sets no sync mode and has synced fields; it syncs as Manual.");
                    }

                    break;
            }

            b.AppendLine($"{i}public override int __SyncMode() {{ return {mode}; }}");
            if (s.OverridesInteract)
            {
                b.AppendLine($"{i}public override bool __HasInteract() {{ return true; }}");
            }

            if (s.OverridesPickupEvents)
            {
                b.AppendLine($"{i}public override bool __HasPickupEvents() {{ return true; }}");
            }
        }

        static void WriteHooks(StringBuilder b, string i, UdonScriptData s, List<ConversionDiagnostic> diagnostics)
        {
            if (s.IsAbstract)
            {
                return;
            }

            // Cilbox calls a hook only when the most-derived class declares it.
            foreach (InheritedHook hook in s.InheritedHooks)
            {
                if (hook.Private)
                {
                    diagnostics.Add(DiagnosticSeverity.Warning, "script.hook.inheritedPrivate",
                        $"{s.Name} inherits a private {hook.Name} that Cilbox will not call.");
                    continue;
                }

                string keyword = hook.Access + (hook.Virtual ? " override" : " new");
                b.AppendLine($"{i}{keyword} void {hook.Name}() {{ base.{hook.Name}(); }}");
            }

            WriteAwake(b, i, s, diagnostics);
        }

        // UdonSharp's GetUdonTypeID: the first 8 bytes of SHA-256 over the type's full name, read as
        // a little-endian long (UdonSharpInternalUtility.GetTypeID). The generic GetUdonTypeID<T>()
        // is replaced with the same constant by the runtime package's IL post-processor.
        public static long UdonTypeId(string fullName)
        {
            using (var sha = System.Security.Cryptography.SHA256.Create())
            {
                byte[] hash = sha.ComputeHash(Encoding.UTF8.GetBytes(fullName));
                long id = 0;
                for (int k = 7; k >= 0; k--) id = (id << 8) | hash[k];
                return id;
            }
        }

        static void WriteTypeId(StringBuilder b, string i, UdonScriptData s)
        {
            // The driver calls Update and its kin in this order (basis-udon's IL post-processor renames them).
            if (s.ExecutionOrder.HasValue)
            {
                b.AppendLine($"{i}public override int __UdonUpdateOrder() {{ return {s.ExecutionOrder.Value}; }}");
            }

            string fullName = string.IsNullOrEmpty(s.Namespace) ? s.Name : s.Namespace + "." + s.Name;
            b.AppendLine($"{i}public override long __UdonTypeID() {{ return {UdonTypeId(fullName)}L; }}");
            b.AppendLine($"{i}public override string __UdonTypeName() {{ return \"{s.Name}\"; }}");
            b.AppendLine();
        }

        // [NetworkCallable] methods: their rate, and dispatch with arguments decoded by the runtime. A
        // null argument becomes default(T), as VRChat documents; an enum arrives as its underlying
        // number (the IL post-processor boxes user enums that way).
        static void WriteCallables(StringBuilder b, string i, UdonScriptData s)
        {
            if (s.CallableMethods.Count == 0)
            {
                return;
            }

            b.AppendLine(i + "public override int __NetworkCallableRate(string eventName)");
            b.AppendLine(i + "{");
            b.AppendLine(i + "    switch (eventName)");
            b.AppendLine(i + "    {");
            foreach (UdonCallableMethod m in s.CallableMethods)
            {
                b.AppendLine($"{i}        case \"{m.Name}\": return {m.MaxEventsPerSecond};");
            }

            b.AppendLine(i + "    }");
            b.AppendLine(i + (s.UserBaseName != null ? "    return base.__NetworkCallableRate(eventName);" : "    return -1;"));
            b.AppendLine(i + "}");
            b.AppendLine();

            b.AppendLine(i + "public override bool __DispatchArgs(string eventName, object[] args)");
            b.AppendLine(i + "{");
            b.AppendLine(i + "    switch (eventName)");
            b.AppendLine(i + "    {");
            foreach (UdonCallableMethod m in s.CallableMethods)
            {
                List<string> arguments = new List<string>();
                for (int k = 0; k < m.ParameterTypes.Count; k++)
                {
                    string type = m.ParameterTypes[k];
                    string value = m.EnumUnderlying[k] != null
                        ? $"({type})({m.EnumUnderlying[k]})args[{k}]"
                        : $"({type})args[{k}]";
                    arguments.Add($"args.Length > {k} && args[{k}] != null ? {value} : default({type})");
                }

                b.AppendLine($"{i}        case \"{m.Name}\": {m.Name}({string.Join(", ", arguments)}); return true;");
            }

            b.AppendLine(i + "    }");
            b.AppendLine(i + (s.UserBaseName != null ? "    return base.__DispatchArgs(eventName, args);" : "    return false;"));
            b.AppendLine(i + "}");
            b.AppendLine();
        }

        // Cilbox finds an interpreted script only through GameObject.GetComponent<T> and
        // TryGetComponent<T> (CilboxUsage.cs:270-319); the other lookups fail the box's export. These
        // reproduce them for this class with that call, in Unity's documented order (depth first for
        // children, nearest first for parents, only active GameObjects unless includeInactive).
        // basis-udon's IL post-processor redirects the generic calls here. GetComponents finds at most
        // one per GameObject, since GetComponent<T> returns the first.
        static void WriteLookups(StringBuilder b, string i, UdonScriptData s)
        {
            string t = s.Name;
            // basis-udon's UdonBehaviour declares these helpers for its own type, so every script's
            // helpers hide an inherited one.
            string hide = "new ";
            const string Go = "global::UnityEngine.GameObject";
            const string Tr = "global::UnityEngine.Transform";
            b.AppendLine($"{i}public {hide}static {t} __UdonInChildren({Go} g, bool includeInactive)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    if (g == null || (!includeInactive && !g.activeInHierarchy)) return null;");
            b.AppendLine($"{i}    {t} found = g.GetComponent<{t}>();");
            b.AppendLine($"{i}    if (found != null) return found;");
            b.AppendLine($"{i}    {Tr} t = g.transform;");
            b.AppendLine($"{i}    for (int k = 0; k < t.childCount; k++)");
            b.AppendLine($"{i}    {{");
            b.AppendLine($"{i}        found = __UdonInChildren(t.GetChild(k).gameObject, includeInactive);");
            b.AppendLine($"{i}        if (found != null) return found;");
            b.AppendLine($"{i}    }}");
            b.AppendLine($"{i}    return null;");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}public {hide}static {t}[] __UdonAllInChildren({Go} g, bool includeInactive)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    return g == null ? new {t}[0] : __UdonCollectChildren(g, includeInactive, new {t}[0]);");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}static {t}[] __UdonCollectChildren({Go} g, bool includeInactive, {t}[] result)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    if (!includeInactive && !g.activeInHierarchy) return result;");
            b.AppendLine($"{i}    {t} found = g.GetComponent<{t}>();");
            b.AppendLine($"{i}    if (found != null) result = __UdonAppend(result, found);");
            b.AppendLine($"{i}    {Tr} t = g.transform;");
            b.AppendLine($"{i}    for (int k = 0; k < t.childCount; k++) result = __UdonCollectChildren(t.GetChild(k).gameObject, includeInactive, result);");
            b.AppendLine($"{i}    return result;");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}public {hide}static {t} __UdonInParent({Go} g, bool includeInactive)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    for ({Tr} t = g != null ? g.transform : null; t != null; t = t.parent)");
            b.AppendLine($"{i}    {{");
            b.AppendLine($"{i}        if (!includeInactive && !t.gameObject.activeInHierarchy) continue;");
            b.AppendLine($"{i}        {t} found = t.gameObject.GetComponent<{t}>();");
            b.AppendLine($"{i}        if (found != null) return found;");
            b.AppendLine($"{i}    }}");
            b.AppendLine($"{i}    return null;");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}public {hide}static {t}[] __UdonAllInParent({Go} g, bool includeInactive)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    {t}[] result = new {t}[0];");
            b.AppendLine($"{i}    for ({Tr} t = g != null ? g.transform : null; t != null; t = t.parent)");
            b.AppendLine($"{i}    {{");
            b.AppendLine($"{i}        if (!includeInactive && !t.gameObject.activeInHierarchy) continue;");
            b.AppendLine($"{i}        {t} found = t.gameObject.GetComponent<{t}>();");
            b.AppendLine($"{i}        if (found != null) result = __UdonAppend(result, found);");
            b.AppendLine($"{i}    }}");
            b.AppendLine($"{i}    return result;");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}public {hide}static {t}[] __UdonAll({Go} g, bool includeInactive)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    {t} found = g != null ? g.GetComponent<{t}>() : null;");
            b.AppendLine($"{i}    return found != null ? new {t}[] {{ found }} : new {t}[0];");
            b.AppendLine($"{i}}}");
            b.AppendLine($"{i}static {t}[] __UdonAppend({t}[] a, {t} item)");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    {t}[] grown = new {t}[a.Length + 1];");
            b.AppendLine($"{i}    for (int k = 0; k < a.Length; k++) grown[k] = a[k];");
            b.AppendLine($"{i}    grown[a.Length] = item;");
            b.AppendLine($"{i}    return grown;");
            b.AppendLine($"{i}}}");
            b.AppendLine();
        }

        // Udon runs OnEnable before Start; Cilbox drops the first OnEnable and runs Awake right before
        // Start. basis-udon's IL post-processor sets this field at the top of OnEnable, so Awake raises
        // the first OnEnable exactly once whether or not Cilbox delivered it.
        public const string OnEnableRanField = "__udonOnEnableRan";

        // Cilbox's export treats a field value of an interpreted class as a component reference
        // (CilboxProxy.SerializeProxyField), so a VRCUrl field cannot be exported. The scene step stores
        // each URL in a string field declared here and leaves the VRCUrl field empty; __UdonAwake
        // rebuilds it before Start.
        public const string UrlFieldPrefix = "__udonUrl_";
        const string UrlType = "global::VRC.SDKBase.VRCUrl";

        static void WriteAwake(StringBuilder b, string i, UdonScriptData s, List<ConversionDiagnostic> diagnostics)
        {
            List<UdonFieldData> urls = s.Fields.FindAll(f => f.TypeName == UrlType || f.TypeName == UrlType + "[]");
            if (urls.Count > 0)
            {
                foreach (UdonFieldData f in urls)
                {
                    string type = f.TypeName.EndsWith("[]") ? "string[]" : "string";
                    b.AppendLine($"{i}[UnityEngine.SerializeField, UnityEngine.HideInInspector] private {type} {UrlFieldPrefix}{f.Name};");
                }

                b.AppendLine($"{i}public override void __UdonAwake()");
                b.AppendLine($"{i}{{");
                b.AppendLine($"{i}    base.__UdonAwake();");
                foreach (UdonFieldData f in urls)
                {
                    string source = UrlFieldPrefix + f.Name;
                    if (f.TypeName.EndsWith("[]"))
                    {
                        b.AppendLine($"{i}    if ({source} != null)");
                        b.AppendLine($"{i}    {{");
                        b.AppendLine($"{i}        {f.Name} = new {UrlType}[{source}.Length];");
                        b.AppendLine($"{i}        for (int k = 0; k < {source}.Length; k++) {f.Name}[k] = new {UrlType}({source}[k]);");
                        b.AppendLine($"{i}    }}");
                    }
                    else
                    {
                        b.AppendLine($"{i}    if ({source} != null) {f.Name} = new {UrlType}({source});");
                    }
                }

                b.AppendLine($"{i}}}");
            }

            if (s.IsAbstract)
            {
                return;
            }

            bool hasOnEnable = s.DeclaredHooks.Contains("OnEnable") || s.InheritedHooks.Exists(h => h.Name == "OnEnable" && !h.Private);
            if (s.DeclaredHooks.Contains("Awake") || s.InheritedHooks.Exists(h => h.Name == "Awake"))
            {
                diagnostics.Add(DiagnosticSeverity.Warning, "script.awake.declared",
                    $"{s.Name} declares Awake, so its URL fields are not rebuilt and its first OnEnable is not raised before Start.");
                return;
            }

            if (hasOnEnable)
            {
                b.AppendLine($"{i}[System.NonSerialized] private bool {OnEnableRanField};");
            }

            b.AppendLine($"{i}void Awake()");
            b.AppendLine($"{i}{{");
            b.AppendLine($"{i}    __UdonAwake();");
            if (hasOnEnable)
            {
                b.AppendLine($"{i}    if (!{OnEnableRanField}) OnEnable();");
            }

            b.AppendLine($"{i}}}");
        }

        static string AliasOf(string name, string[] table)
        {
            foreach (string entry in table)
            {
                if (entry == name)
                {
                    return "_" + char.ToLowerInvariant(name[0]) + name.Substring(1);
                }
            }

            return null;
        }

        static string Write(UdonFieldData f, string value)
        {
            switch (f.Wire)
            {
                case UdonWireKind.String: return $"writer.Write({value} != null ? {value} : \"\");";
                case UdonWireKind.Vector2: return $"{{ writer.Write({value}.x); writer.Write({value}.y); }}";
                case UdonWireKind.Vector3: return $"{{ writer.Write({value}.x); writer.Write({value}.y); writer.Write({value}.z); }}";
                case UdonWireKind.Vector4:
                case UdonWireKind.Quaternion:
                    return $"{{ writer.Write({value}.x); writer.Write({value}.y); writer.Write({value}.z); writer.Write({value}.w); }}";
                case UdonWireKind.Color: return $"{{ writer.Write({value}.r); writer.Write({value}.g); writer.Write({value}.b); writer.Write({value}.a); }}";
                case UdonWireKind.Color32: return $"{{ writer.Write({value}.r); writer.Write({value}.g); writer.Write({value}.b); writer.Write({value}.a); }}";
                case UdonWireKind.Enum: return $"writer.Write(({f.EnumUnderlying}){value});";
                default: return $"writer.Write({value});";
            }
        }

        static string Read(UdonFieldData f)
        {
            switch (f.Wire)
            {
                case UdonWireKind.Bool: return "reader.ReadBoolean()";
                case UdonWireKind.Char: return "reader.ReadChar()";
                case UdonWireKind.Byte: return "reader.ReadByte()";
                case UdonWireKind.SByte: return "reader.ReadSByte()";
                case UdonWireKind.Short: return "reader.ReadInt16()";
                case UdonWireKind.UShort: return "reader.ReadUInt16()";
                case UdonWireKind.Int: return "reader.ReadInt32()";
                case UdonWireKind.UInt: return "reader.ReadUInt32()";
                case UdonWireKind.Long: return "reader.ReadInt64()";
                case UdonWireKind.ULong: return "reader.ReadUInt64()";
                case UdonWireKind.Float: return "reader.ReadSingle()";
                case UdonWireKind.Double: return "reader.ReadDouble()";
                case UdonWireKind.String: return "reader.ReadString()";
                case UdonWireKind.Vector2: return "new UnityEngine.Vector2(reader.ReadSingle(), reader.ReadSingle())";
                case UdonWireKind.Vector3: return "new UnityEngine.Vector3(reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle())";
                case UdonWireKind.Vector4: return "new UnityEngine.Vector4(reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle())";
                case UdonWireKind.Quaternion: return "new UnityEngine.Quaternion(reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle())";
                case UdonWireKind.Color: return "new UnityEngine.Color(reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle(), reader.ReadSingle())";
                case UdonWireKind.Color32: return "new UnityEngine.Color32(reader.ReadByte(), reader.ReadByte(), reader.ReadByte(), reader.ReadByte())";
                case UdonWireKind.Enum:
                    string element = f.IsArray ? f.TypeName.Substring(0, f.TypeName.Length - 2) : f.TypeName;
                    return $"({element}){ReadUnderlying(f.EnumUnderlying)}";
                default: return "default";
            }
        }

        static string ReadUnderlying(string underlying)
        {
            switch (underlying)
            {
                case "byte": return "reader.ReadByte()";
                case "sbyte": return "reader.ReadSByte()";
                case "short": return "reader.ReadInt16()";
                case "ushort": return "reader.ReadUInt16()";
                case "uint": return "reader.ReadUInt32()";
                case "long": return "reader.ReadInt64()";
                case "ulong": return "reader.ReadUInt64()";
                default: return "reader.ReadInt32()";
            }
        }
    }
